package com.pox.kernelmanager.util

import android.content.Context
import android.content.Intent
import android.net.Uri

/**
 * Telegram sharing utilities for the Pox Kernel Manager.
 * 
 * Shares text or files to Telegram via the system share sheet.
 * Falls back to any app that accepts the intent type if Telegram is not installed.
 */
object TelegramShare {

    /**
     * Show the system share sheet.
     *
     * Callers may pass the application context (the ViewModels do), which
     * requires [Intent.FLAG_ACTIVITY_NEW_TASK]; without it Android throws
     * `AndroidRuntimeException: Calling startActivity() from outside of an
     * Activity context`.
     */
    private fun launchChooser(context: Context, intent: Intent, title: String) {
        val chooser = Intent.createChooser(intent, title).apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        context.startActivity(chooser)
    }

    /** Share plain text to Telegram via system share chooser. */
    fun shareText(context: Context, text: String, title: String = "Pox Kernel") {
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_TEXT, text)
            putExtra(Intent.EXTRA_SUBJECT, title)
        }
        launchChooser(context, intent, "Share to Telegram")
    }

    /** Share a zip file to Telegram via the system share chooser. */
    fun shareFile(context: Context, uri: Uri, mimeType: String = "application/zip") {
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = mimeType
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        launchChooser(context, intent, "Share to Telegram")
    }

    /** Share kernel build info as formatted text. */
    fun shareBuildInfo(context: Context, variant: String, commit: String, gofileLink: String?, release: Boolean) {
        val tb = StringBuilder()
        tb.append("Pox Kernel Build Info\n")
        tb.append("===================\n")
        tb.append("Variant: $variant\n")
        tb.append("Commit: ${commit.take(8)}\n")
        tb.append("Build: ${if (release) "Release" else "Debug"}\n")
        tb.append("GoFile: $gofileLink\n")
        tb.append("\nGenerated by Pox Kernel Telegram Build Bot\n")
        shareText(context, tb.toString(), "Pox Build Info")
    }

    /** Share a simple status line to Telegram. */
    fun shareStatus(context: Context, status: String) {
        shareText(context, status, "Pox Kernel Status")
    }
}
